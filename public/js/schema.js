// 卡片类型 → 默认存放文件夹（与仓库的分类方式一致）
export function folderForType(type, fm = {}) {
  switch (type) {
    case '书籍': {
      const i = PROP_VALUES.书籍.indexOf(fm.书籍);
      return i >= 0 ? `01_书籍电影分类/${String(i + 1).padStart(2, '0')}_${PROP_VALUES.书籍[i]}` : '01_书籍电影分类';
    }
    case '电影': case '电视剧': case '纪录片': return '01_书籍电影分类/14_电影记录';
    case '人物': return '02_永久知识卡片盒/01_人物类';
    case '概念': return '02_永久知识卡片盒/02_概念类';
    case '主题': return '00_闪念收集箱/00_主题学习';
    case '输出文章': return '05_输出文章/01_我的公众号写作';
    default: return '';
  }
}

